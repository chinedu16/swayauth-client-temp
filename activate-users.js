async function activateUsers() {
  for (const user of users) {
    try {
      const response = await fetch('http://localhost:8000/v1/auth/register/verify', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          reference: user.id,
          token: 'verified'  // Assuming a dummy token for verification
        }),
      });

      const result = await response.json();
      console.log(`Activated ${user.email}: ${result.message || result.error || 'Success'}`);
    } catch (error) {
      console.error(`Failed to activate ${user.email}: ${error.message}`);
    }
  }
}

